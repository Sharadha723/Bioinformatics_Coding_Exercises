def parse_data(seq):
    highest_GC = 0
    final_id = None
    for data in seq.strip().split('>'):
        if not data:
            continue
        lines = data.splitlines()
        rosalind_id = lines[0]
        sequence = ''.join(lines[1:])
        perc_GC = round(((sequence.count('G')+sequence.count('C'))/len(sequence))*100,6)
        
        if perc_GC > highest_GC:
            highest_GC = perc_GC
            final_id = rosalind_id
            
    return (final_id, highest_GC)

